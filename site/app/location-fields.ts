export function hasValidLocation(value: string, unit = "") {
  const normalized = value.trim();
  if (!normalized) return false;
  if (unit.trim() && normalized.localeCompare(unit.trim(), "pt-BR", { sensitivity: "base" }) === 0) return false;
  return !invalidLocationValues.some((pattern) => pattern.test(normalized));
}

export function locationFromEquipment(equipment: string): EquipmentLocation | null {
  const code = equipment.match(/\b(\d{5})/)?.[1];
  return code ? equipmentLocations[code] || null : null;
}
